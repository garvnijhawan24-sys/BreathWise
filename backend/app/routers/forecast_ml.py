"""
FastAPI router for local Machine Learning forecasts and status.
Exposes GET /api/forecast/ml with validated parameters, recent observation extraction,
and transparent model status.
"""
import logging
from typing import Optional
from fastapi import APIRouter, Query
import pandas as pd

from app.schemas import MLForecastResponse
from app.ml.predict import get_ml_forecast

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/forecast", tags=["Machine Learning Forecast"])


@router.get("/ml", response_model=MLForecastResponse)
async def get_machine_learning_forecast(
    station_id: Optional[int] = Query(
        default=None,
        description="Optional OpenAQ ground station ID for station-specific forecast",
    ),
    hours: int = Query(
        default=24,
        ge=1,
        le=72,
        description="Forecast horizon hours (1 to 72)",
    ),
) -> MLForecastResponse:
    """
    Returns the short-term PM2.5 forecast generated by the local Random Forest model.
    Transparently reports 'model_not_trained' when no validated historical model is present,
    or 'insufficient_data' if recent 24-hour observation history cannot be obtained.
    """
    recent_series: Optional[pd.DataFrame] = None

    if station_id is not None:
        try:
            from app.services.openaq import fetch_station_measurements
            meas_resp = await fetch_station_measurements(
                station_id=station_id,
                limit=48,
                use_cache=True,
            )
            pm25_records = [
                {"timestamp": m.observed_at, "pm2_5": m.value}
                for m in meas_resp.measurements
                if m.parameter.lower() in ("pm25", "pm2_5", "pm2.5") and m.value is not None
            ]
            if pm25_records:
                recent_series = pd.DataFrame(pm25_records)
        except Exception as exc:
            # If OpenAQ is unconfigured or unreachable, recent_series remains None
            logger.debug(f"Could not retrieve recent observations for station #{station_id}: {exc}")
            recent_series = None

    forecast_data = get_ml_forecast(
        station_id=station_id,
        horizon_hours=hours,
        recent_series=recent_series,
    )
    return MLForecastResponse(**forecast_data)
